#!/usr/bin/env python3
"""Generate docs/field-trace.md from the API's OpenAPI document: every client-visible field whose
schema is a SourcedValue, the response model it sits in, its owner (table.column) and the source_ref
kinds it may carry, both declared on the field with json_schema_extra={"owner": ..., "ref_kinds": [...]}.

--check exits 1 when the file on disk differs or a SourcedValue field has no owner (CI and the watcher)."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "apps" / "api"))

HEADER = """# Field trace

Generated by `tools/dev/field-trace.py` from the API response models. Do not edit by hand. CI fails on drift or on a field with no owner.

| Client-visible field | Response model | Table.column | Allowed source_ref kinds |
| --- | --- | --- | --- |
"""


def rows() -> tuple[list[str], list[str]]:
    from ergplan.platform.app import create_app

    spec = create_app().openapi()
    schemas = spec.get("components", {}).get("schemas", {})
    out, orphans = [], []
    for model, schema in sorted(schemas.items()):
        for field, prop in sorted((schema.get("properties") or {}).items()):
            ref = prop.get("$ref") or next((x.get("$ref") for x in prop.get("anyOf", []) if "$ref" in x), None)
            items = prop.get("items", {}).get("$ref") if prop.get("type") == "array" else None
            target = (ref or items or "").rsplit("/", 1)[-1]
            if target != "SourcedValue":
                continue
            owner = prop.get("owner")
            kinds = ", ".join(prop.get("ref_kinds") or [])
            if not owner:
                orphans.append(f"{model}.{field}")
            out.append(f"| `{field}` | {model} | {owner or '**no owner**'} | {kinds or '—'} |")
    return out, orphans


def render() -> tuple[str, list[str]]:
    r, orphans = rows()
    body = "\n".join(r) if r else "| (no SourcedValue fields yet) | | | |"
    return HEADER + body + "\n", orphans


def main() -> int:
    text, orphans = render()
    target = ROOT / "docs" / "field-trace.md"
    if "--check" in sys.argv:
        bad = False
        if target.read_text() != text:
            print("field-trace: docs/field-trace.md is stale; run tools/dev/field-trace.py")
            bad = True
        if orphans:
            print("field-trace: fields with no owner:", ", ".join(orphans))
            bad = True
        print("field-trace: OK" if not bad else "field-trace: FAIL")
        return 1 if bad else 0
    target.write_text(text)
    print(f"field-trace: wrote {len(text.splitlines()) - 5} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
